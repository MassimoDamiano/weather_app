/*
Design Tokens
¿Qué son?

Los Design Tokens son constantes que representan los valores de diseño de una aplicación. 
En lugar de escribir valores directamente en el código (hardcodeados), 
se centralizan en una clase para mantener consistencia y facilitar el mantenimiento.

Beneficios
Mantiene consistencia visual.
Facilita el mantenimiento.
Evita valores duplicados.
Permite modificar toda la aplicación desde un único lugar.
Hace que el código sea más legible.
¿Dónde se usa?

Los Design Tokens pueden utilizarse en:

Padding
Margin
SizedBox
BorderRadius
Separación entre widgets
Espaciado interno de tarjetas
Diámetros de avatares
Tamaños de iconos (cuando corresponda)
*/